"""
News Manager agent prompt context.

这个模块包含新闻管理代理的 AI prompt 字符串。
"""


def get_news_filter_prompt_messages() -> list[tuple[str, str]]:
    """
    返回新闻筛选的 prompt 消息列表。
    
    返回:
        包含 system 和 human 消息的列表，用于筛选与股票相关的新闻
    """
    return [
        (
            "system",
            """
            你是一名金融新闻分析师，需要从大量新闻中筛选出与特定股票相关的新闻。
            
            筛选标准：
            1. 直接相关：新闻标题或标签中明确提到该股票代码或公司名称
            2. 业务相关：新闻涉及该公司的主要业务领域、行业动态
            3. 宏观影响：新闻涉及可能影响该股票的国家政策、经济数据、地缘政治等
            4. 市场情绪：新闻可能影响整体市场情绪，进而影响该股票
            
            请仔细分析每条新闻的标题、标签，判断是否与股票相关。
            只选择真正可能影响该股票价格的新闻，避免选择无关新闻。
            """
        ),
        (
            "human",
            "股票代码：{ticker}\n\n"
            "所有新闻：\n{all_news}\n\n"
            "请从以上新闻中筛选出与股票 {ticker} 相关的新闻。"
            "筛选标准："
            "1. 直接相关：新闻标题或标签中明确提到该股票代码或公司名称"
            "2. 业务相关：新闻涉及该公司的主要业务领域、行业动态"
            "3. 宏观影响：新闻涉及可能影响该股票的国家政策、经济数据、地缘政治等"
            "4. 市场情绪：新闻可能影响整体市场情绪，进而影响该股票"
            "\n"
            "返回格式：JSON 对象，包含 'news' 字段，值为新闻数组。"
            "每个新闻对象应保持原始结构（包含 datetime, title, raw_time, labels, news_id, url 等字段），"
            "并添加以下字段："
            "1. 'title_cn': 标题的中文翻译（如果标题是英文，必须提供准确的中文翻译）"
            "2. 'relevance_reason': 说明该新闻入选的理由（仅中文，不需要英文）"
            "\n"
            "relevance_reason 格式示例（仅中文）："
            "- \"直接提及股票代码\""
            "- \"业务相关：涉及支付行业动态\""
            "- \"宏观影响：中国政策变化\""
            "- \"市场情绪：科技股整体走势\""
            "\n"
            "如果没有任何相关新闻，返回 {{'news': []}}。"
        ),
    ]

